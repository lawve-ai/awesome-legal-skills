"""`.lacase` case bundles: export, import and continuity between hosts (LA-019, R2/R9/R17, pipeline 17).

A bundle is a ZIP of: `manifest.json`, `case.json`, `db.jsonl` (the canonical row dump: one JSON
object per row, tables in dependency order, rows in insertion order), optional `extraction.json`,
`review/*.json` exports and — only with an explicit `with_originals` — `corpus/*` frozen files.
Nothing in a bundle is ever executed: the dump is parsed row by row, every column name is checked
against the table definition generated by this code, values are inserted with bound parameters,
and the rebuilt database is then verified (schemas, passage hashes, corpus hash, foreign keys,
hash chain, `approved_set_hash`, `chain_head`) before anything is published.

Import builds the new case in a sibling staging directory and publishes it with one rename; it
never merges into or overwrites an existing case, and a failed import leaves nothing behind.
Review rows are copied verbatim: the import neither raises nor re-derives an evidence class.
The manifest carries no hash of a report (that would be circular): `reproduction_manifest` binds
a report hash to a bundle hash and code version outside the bundle for the exhibit package.
"""
from __future__ import annotations

import hashlib
import io
import json
import os
import re
import shutil
import sqlite3
import stat
import uuid
import zipfile
from pathlib import Path
from typing import Any, Callable

from . import __version__
from .ingest import _doc_filename
from .repository import SCHEMA_DIR, SCHEMA_OF, SCHEMA_VERSION, SQL_FILE, ReadRepository, _connect
from .runtime import EXIT_INTEGRITY, EXIT_PATH, EXIT_USAGE, LaError, atomic_write, canonical_json, sha256_hex, sha256_obj
from .validation import admit, load_registry

FORMAT = "lacase"
FORMAT_VERSION = 1
TABLE_ORDER = ["meta", "runs", "steps", "documents", "passages", "family_memberships", "event_time_assessments",
               "search_records", "value_records", "claims", "observation_sets", "observations", "perspectives",
               "hypotheses", "assumptions", "assessments", "tests", "reviews", "prov_edges", "proposals", "chain",
               "run_heads"]
LIMITS = {"max_members": 50_000, "max_total_bytes": 1 << 30, "max_member_bytes": 512 << 20, "max_ratio": 200,
          "max_rows": 5_000_000, "max_line_bytes": 16 << 20}
FIXED_TIME = (1980, 1, 1, 0, 0, 0)
_STATIC = {"manifest.json", "case.json", "db.jsonl", "extraction.json"}
_SAFE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,150}$")
_DEVICES = {"CON", "PRN", "AUX", "NUL", *(f"COM{i}" for i in range(1, 10)), *(f"LPT{i}" for i in range(1, 10))}

_after_stage: Callable[[str], None] | None = None  # test seam to simulate an interruption


def _stage(name: str) -> None:
    if _after_stage is not None:
        _after_stage(name)


def _invalid(detail: str, **ids: str) -> LaError:
    return LaError("E_BUNDLE_INVALID", "The case bundle is invalid or unsupported.",
                   "Paczka sprawy jest nieprawidłowa lub nieobsługiwana.", EXIT_INTEGRITY, {"detail": detail, **ids})


def _err(code: str, en: str, pl: str, exit_code: int = EXIT_USAGE, **ids: str) -> LaError:
    return LaError(code, en, pl, exit_code, ids or None)


def _safe_part(part: str) -> bool:
    return bool(_SAFE.match(part)) and not part.endswith(".") and part.split(".")[0].upper() not in _DEVICES


def check_member_name(name: str) -> None:
    """Allow-list of member names; everything else (traversal, absolute, device, odd) is invalid."""
    if name in _STATIC:
        return
    parts = name.split("/")
    if len(parts) == 2 and parts[0] in ("review", "corpus") and _safe_part(parts[1]):
        if parts[0] == "review" and not parts[1].endswith(".json"):
            raise _invalid("member_name", name=name)
        return
    raise _invalid("member_name", name=name)


# --- export ---------------------------------------------------------------------------------------

def _dump_rows(conn: sqlite3.Connection) -> list[tuple[str, dict[str, Any]]]:
    out: list[tuple[str, dict[str, Any]]] = []
    for table in TABLE_ORDER:
        cur = conn.execute(f"SELECT * FROM {table} ORDER BY rowid")  # noqa: S608 whitelisted
        names = [c[0] for c in cur.description]
        out += [(table, dict(zip(names, row))) for row in cur]
    return out


def export_case(case_dir: Path | str, out_path: Path | str, *, with_originals: bool = False) -> dict[str, Any]:
    root = Path(case_dir)
    target = Path(out_path)
    if target.suffix != ".lacase":
        raise _err("E_BUNDLE_NAME", "The bundle file name must end in .lacase.", "Nazwa pliku paczki musi kończyć się .lacase.")
    if target.exists():
        raise _err("E_OUT_EXISTS", "The output file already exists; it is never overwritten.",
                   "Plik wyjściowy już istnieje; nigdy nie jest nadpisywany.")
    from .profile import load_profile
    profile = load_profile(root)
    rd = ReadRepository(root / "case.db", profile["case_id"])
    try:
        rd.assert_chain_ok()
        raw = _connect(str(root / "case.db"), readonly=True)  # the dump is the whole history, proposals included
        try:
            rows = _dump_rows(raw)
        finally:
            raw.close()
        approved_set_hash, chain_head = rd.approved_set_hash(), rd.chain_head()
        documents = rd.frozen_rows("documents")
        reviews = rd.review_rows()
    finally:
        rd.close()
    members: dict[str, bytes] = {
        "case.json": (root / "case.json").read_bytes(),
        "db.jsonl": b"".join(canonical_json({"table": t, "row": r}) + b"\n" for t, r in rows),
    }
    if (root / "extraction.json").is_file():
        members["extraction.json"] = (root / "extraction.json").read_bytes()
    review_dir = root / "review"
    if review_dir.is_dir():
        for f in sorted(review_dir.glob("export-*.json")):
            if f.is_file() and not f.is_symlink() and _safe_part(f.name):
                members[f"review/{f.name}"] = f.read_bytes()
    expected = [{"document_id": d["id"], "sha256": d["sha256"], "size_bytes": d["size_bytes"], "kind": d["kind"],
                 "file": _doc_filename(d["id"])} for d in sorted(documents, key=lambda d: d["id"])]
    if with_originals:
        for d in expected:
            path = root / "corpus" / d["file"]
            data = path.read_bytes() if path.is_file() and not path.is_symlink() else None
            if data is None or hashlib.sha256(data).hexdigest() != d["sha256"]:
                raise _err("E_BUNDLE_ORIGINALS", "A frozen file is missing or no longer matches its SHA-256.",
                           "Brakuje zamrożonego pliku albo nie zgadza się on z SHA-256.", EXIT_INTEGRITY,
                           document_id=d["document_id"])
            members[f"corpus/{d['file']}"] = data
    manifest = {
        "format": FORMAT, "format_version": FORMAT_VERSION, "case_id": profile["case_id"],
        "schema_version": SCHEMA_VERSION, "code_version": __version__, "approved_set_hash": approved_set_hash,
        "chain_head": chain_head, "with_originals": with_originals, "documents": expected,
        "tables": {t: sum(1 for x, _ in rows if x == t) for t in TABLE_ORDER},
        "reviews": len(reviews),
        "files": {n: {"sha256": sha256_hex(b), "size": len(b)} for n, b in sorted(members.items())},
        "report_hook": {"report_hash_in_bundle": False, "see": "reproduction_manifest"},
        "created_at": _now(),
    }
    members["manifest.json"] = canonical_json(manifest) + b"\n"
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for name in sorted(members):
            info = zipfile.ZipInfo(name, FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            zf.writestr(info, members[name], compresslevel=6)
    data = buf.getvalue()
    _stage("zip")
    target.parent.mkdir(parents=True, exist_ok=True)
    tmp = target.with_name(f".{target.name}.{uuid.uuid4().hex[:8]}.tmp")
    try:
        with open(tmp, "wb") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, target)
    finally:
        if tmp.exists():
            tmp.unlink()
    marker = {"reviews_exported": len(reviews), "bundle_sha256": sha256_hex(data),
              "approved_set_hash": approved_set_hash, "chain_head": chain_head}
    atomic_write(root, "export_marker.json", canonical_json(marker) + b"\n")
    return {"ok": True, "path": str(target), "bundle_sha256": sha256_hex(data), "approved_set_hash": approved_set_hash,
            "chain_head": chain_head, "with_originals": with_originals,
            "originals_included": len(expected) if with_originals else 0,
            "originals_pending": 0 if with_originals else len(expected), "reviews": len(reviews)}


def _now() -> str:
    import datetime
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


# --- reading an untrusted archive ---------------------------------------------------------------------

def _read_members(path: Path, limits: dict[str, int]) -> dict[str, bytes]:
    try:
        zf = zipfile.ZipFile(path)
    except (zipfile.BadZipFile, OSError) as e:
        raise _invalid("not_a_zip") from e
    out: dict[str, bytes] = {}
    with zf:
        infos = zf.infolist()
        if len(infos) > limits["max_members"]:
            raise _invalid("too_many_members")
        seen: set[str] = set()
        total = 0
        for info in infos:
            name = info.filename
            check_member_name(name)
            folded = name.casefold()
            if folded in seen:
                raise _invalid("duplicate_member", name=name)
            seen.add(folded)
            if info.flag_bits & 0x1:
                raise _invalid("encrypted_member", name=name)
            if stat.S_ISLNK(info.external_attr >> 16) or info.is_dir():
                raise _invalid("link_or_directory_member", name=name)
            if info.file_size > limits["max_member_bytes"]:
                raise _invalid("member_too_large", name=name)
            if info.compress_size and info.file_size / info.compress_size > limits["max_ratio"]:
                raise _invalid("compression_ratio", name=name)
            total += info.file_size
            if total > limits["max_total_bytes"]:
                raise _invalid("total_too_large")
            buf = bytearray()
            try:
                with zf.open(info) as fh:
                    while True:
                        chunk = fh.read(1 << 20)
                        if not chunk:
                            break
                        buf += chunk
                        if len(buf) > min(info.file_size, limits["max_member_bytes"]):
                            raise _invalid("member_size_lies", name=name)
            except (zipfile.BadZipFile, OSError, EOFError, RuntimeError, NotImplementedError) as e:
                raise _invalid("member_unreadable", name=name) from e
            out[name] = bytes(buf)
    return out


def _parse_manifest(members: dict[str, bytes]) -> dict[str, Any]:
    if "manifest.json" not in members:
        raise _invalid("no_manifest")
    try:
        manifest = json.loads(members["manifest.json"].decode("utf-8"))
    except (UnicodeDecodeError, ValueError) as e:
        raise _invalid("manifest_json") from e
    if not isinstance(manifest, dict) or manifest.get("format") != FORMAT:
        raise _invalid("not_a_lacase")
    if manifest.get("format_version") != FORMAT_VERSION:
        raise _invalid("format_version", found=str(manifest.get("format_version")))
    sv = manifest.get("schema_version")
    if not isinstance(sv, int) or isinstance(sv, bool) or sv > SCHEMA_VERSION or sv < 1:
        raise _invalid("schema_version", found=str(sv), supported=str(SCHEMA_VERSION))
    files = manifest.get("files")
    if not isinstance(files, dict) or set(files) != set(members) - {"manifest.json"}:
        raise _invalid("file_list_mismatch")
    for name, meta in files.items():
        if (not isinstance(meta, dict) or meta.get("sha256") != sha256_hex(members[name])
                or meta.get("size") != len(members[name])):
            raise _invalid("file_hash_mismatch", name=name)
    for key in ("case_id", "approved_set_hash", "chain_head"):
        if not isinstance(manifest.get(key), str) or not manifest[key]:
            raise _invalid("manifest_field", field=key)
    if not isinstance(manifest.get("documents"), list) or not isinstance(manifest.get("with_originals"), bool):
        raise _invalid("manifest_field", field="documents")
    return manifest


def inspect_bundle(bundle: Path | str, *, limits: dict[str, int] | None = None) -> dict[str, Any]:
    """Validate the archive envelope and manifest only (no database is built)."""
    lim = {**LIMITS, **(limits or {})}
    members = _read_members(Path(bundle), lim)
    m = _parse_manifest(members)
    return {"ok": True, "case_id": m["case_id"], "schema_version": m["schema_version"], "code_version": m["code_version"],
            "approved_set_hash": m["approved_set_hash"], "chain_head": m["chain_head"],
            "with_originals": m["with_originals"], "documents": len(m["documents"]), "members": len(members)}


# --- import -------------------------------------------------------------------------------------------

def _columns(conn: sqlite3.Connection, table: str) -> list[str]:
    return [r[1] for r in conn.execute(f"PRAGMA table_info({table})")]  # noqa: S608 whitelisted


def _load_rows(conn: sqlite3.Connection, data: bytes, limits: dict[str, int]) -> dict[str, int]:
    cols = {t: _columns(conn, t) for t in TABLE_ORDER}
    counts = {t: 0 for t in TABLE_ORDER}
    last = -1
    n = 0
    for lineno, line in enumerate(data.split(b"\n")):
        if not line:
            continue
        if len(line) > limits["max_line_bytes"]:
            raise _invalid("line_too_long", line=str(lineno + 1))
        n += 1
        if n > limits["max_rows"]:
            raise _invalid("too_many_rows")
        try:
            rec = json.loads(line.decode("utf-8"))
        except (UnicodeDecodeError, ValueError) as e:
            raise _invalid("dump_line_json", line=str(lineno + 1)) from e
        if not isinstance(rec, dict) or set(rec) != {"table", "row"} or rec["table"] not in cols:
            raise _invalid("dump_line_shape", line=str(lineno + 1))
        table, row = rec["table"], rec["row"]
        pos = TABLE_ORDER.index(table)
        if pos < last:
            raise _invalid("dump_table_order", line=str(lineno + 1))
        last = pos
        if not isinstance(row, dict) or set(row) != set(cols[table]):
            raise _invalid("dump_columns", table=table, line=str(lineno + 1))
        if any(not (v is None or (isinstance(v, (str, int)) and not isinstance(v, bool))) for v in row.values()):
            raise _invalid("dump_value_type", table=table, line=str(lineno + 1))
        names = cols[table]
        try:
            conn.execute(f"INSERT INTO {table} ({', '.join(names)}) VALUES ({', '.join('?' * len(names))})",  # noqa: S608
                         [row[c] for c in names])
        except sqlite3.DatabaseError as e:
            raise _invalid("dump_row_rejected", table=table, line=str(lineno + 1), error=type(e).__name__) from e
        counts[table] += 1
    return counts


def _verify_rebuilt(db: Path, case_id: str, manifest: dict[str, Any], counts: dict[str, int]) -> None:
    conn = sqlite3.connect(db)
    try:
        if conn.execute("PRAGMA foreign_key_check").fetchall():
            raise _invalid("foreign_keys")
        meta = conn.execute("SELECT case_id, schema_version FROM meta").fetchall()
        if meta != [(case_id, manifest["schema_version"])]:
            raise _invalid("meta_mismatch")
        if counts != manifest.get("tables"):
            raise _invalid("table_counts")
        registry = load_registry(SCHEMA_DIR)
        for table, schema in SCHEMA_OF.items():
            for (body_json,) in conn.execute(f"SELECT body_json FROM {table}"):  # noqa: S608 whitelisted
                body = json.loads(body_json)
                if body.get("case_id") != case_id:
                    raise _invalid("foreign_case_row", table=table)
                try:
                    admit(body, f"la:schema/{schema}/v1", registry)
                except LaError as e:
                    raise _invalid("schema_invalid_row", table=table, id=str(body.get("id", ""))) from e
        docs = [json.loads(b) for (b,) in conn.execute("SELECT body_json FROM documents ORDER BY id")]
        for (body_json,) in conn.execute("SELECT body_json FROM passages"):
            p = json.loads(body_json)
            if sha256_hex(p["text"].encode("utf-8")) != p["text_sha256"]:
                raise _invalid("passage_hash", id=p["id"])
        last_run = conn.execute("SELECT corpus_hash FROM runs ORDER BY rowid DESC LIMIT 1").fetchone()
        if docs and last_run and sha256_obj(sorted(docs, key=lambda d: d["id"])) != last_run[0]:
            raise _invalid("corpus_hash")
        if sorted(d["id"] for d in docs) != sorted(d["document_id"] for d in manifest["documents"]):
            raise _invalid("manifest_documents")
    finally:
        conn.close()
    rd = ReadRepository(db, case_id)
    try:
        verdict = rd.verify()
        if not verdict.ok:
            raise LaError("E_CHAIN_BROKEN", "Hash chain verification failed.",
                          "Weryfikacja łańcucha haszy nie powiodła się.", EXIT_INTEGRITY,
                          {"first_broken_id": verdict.first_broken_id or "", "reason": verdict.reason or ""})
        if rd.approved_set_hash() != manifest["approved_set_hash"]:
            raise _invalid("approved_set_hash_mismatch")
        if rd.chain_head() != manifest["chain_head"]:
            raise _invalid("chain_head_mismatch")
    finally:
        rd.close()


def import_case(bundle: Path | str, target_dir: Path | str, *, limits: dict[str, int] | None = None) -> dict[str, Any]:
    lim = {**LIMITS, **(limits or {})}
    target = Path(target_dir)
    if os.path.lexists(target):
        raise _err("E_CASE_EXISTS", "The target case directory already exists; bundles are never merged or overwritten.",
                   "Katalog docelowy już istnieje; paczki nigdy nie są scalane ani nadpisywane.", EXIT_PATH)
    members = _read_members(Path(bundle), lim)
    manifest = _parse_manifest(members)
    case_id = manifest["case_id"]
    try:
        case_json = json.loads(members["case.json"].decode("utf-8"))
    except (KeyError, UnicodeDecodeError, ValueError) as e:
        raise _invalid("case_json") from e
    if not isinstance(case_json, dict) or case_json.get("case_id") != case_id or "db.jsonl" not in members:
        raise _invalid("case_identity")
    parent = target.parent
    parent.mkdir(parents=True, exist_ok=True)
    for stale in parent.glob(f".import-{target.name}-*"):  # leftovers of an interrupted import of this target
        shutil.rmtree(stale, ignore_errors=True)
    staging = parent / f".import-{target.name}-{uuid.uuid4().hex[:8]}"
    staging.mkdir()
    try:
        db = staging / "case.db"
        conn = sqlite3.connect(db, isolation_level=None)
        try:
            conn.executescript(SQL_FILE.read_text(encoding="utf-8"))
            conn.execute("PRAGMA foreign_keys = OFF")
            conn.execute("BEGIN")
            counts = _load_rows(conn, members["db.jsonl"], lim)
            conn.execute("COMMIT")
        finally:
            conn.close()
        _stage("rows")
        _verify_rebuilt(db, case_id, manifest, counts)
        _stage("verified")
        (staging / "case.json").write_bytes(members["case.json"])
        docs = sorted((json.loads(b) for (b,) in _rows(db, "SELECT body_json FROM documents")), key=lambda d: d["id"])
        (staging / "manifest.json").write_bytes(canonical_json({"corpus_hash": sha256_obj(docs), "documents": docs}) + b"\n")
        if "extraction.json" in members:
            (staging / "extraction.json").write_bytes(members["extraction.json"])
        for name, data in members.items():
            if name.startswith("review/"):
                (staging / "review").mkdir(exist_ok=True)
                (staging / name).write_bytes(data)
        pending = []
        by_file = {d["file"]: d for d in manifest["documents"]}
        have = {n[len("corpus/"):] for n in members if n.startswith("corpus/")}
        if have and not manifest["with_originals"]:
            raise _invalid("corpus_without_flag")
        if have - set(by_file):
            raise _invalid("corpus_unknown_file")
        if manifest["with_originals"] and have != set(by_file):
            raise _invalid("corpus_incomplete")
        (staging / "corpus").mkdir()
        for fname in sorted(have):
            if sha256_hex(members[f"corpus/{fname}"]) != by_file[fname]["sha256"]:
                raise _invalid("corpus_hash_mismatch", file=fname)
            (staging / "corpus" / fname).write_bytes(members[f"corpus/{fname}"])
        pending = sorted(d["document_id"] for d in manifest["documents"] if d["file"] not in have)
        classes: dict[str, int] = {}
        rd = ReadRepository(db, case_id)
        try:
            for r in rd.review_rows():
                classes[r["evidence_class"]] = classes.get(r["evidence_class"], 0) + 1
        finally:
            rd.close()
        record = {"imported_from_bundle_sha256": sha256_hex(Path(bundle).read_bytes()),
                  "approved_set_hash": manifest["approved_set_hash"], "chain_head": manifest["chain_head"],
                  "code_version_exported": manifest["code_version"], "originals_pending": pending,
                  "evidence_classes_as_recorded": dict(sorted(classes.items())),
                  "evidence_class_note": "copied verbatim from the bundle; not verified or raised by the import"}
        (staging / "import.json").write_bytes(canonical_json(record) + b"\n")
        _stage("staged")
        try:
            os.rename(staging, target)  # one atomic publication; fails if the target appeared meanwhile
        except OSError as e:
            raise _err("E_CASE_EXISTS", "The target case directory already exists; bundles are never merged or overwritten.",
                       "Katalog docelowy już istnieje; paczki nigdy nie są scalane ani nadpisywane.", EXIT_PATH) from e
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    return {"ok": True, "case_id": case_id, "path": str(target), "approved_set_hash": manifest["approved_set_hash"],
            "chain_head": manifest["chain_head"], "originals_pending": pending,
            "originals_awaiting_upload": bool(pending), "evidence_classes": dict(sorted(classes.items()))}


def _rows(db: Path, sql: str) -> list[tuple[Any, ...]]:
    conn = sqlite3.connect(db)
    try:
        return conn.execute(sql).fetchall()
    finally:
        conn.close()


# --- originals -----------------------------------------------------------------------------------------

def pending_originals(case_dir: Path | str) -> list[str]:
    root = Path(case_dir)
    from .profile import load_profile
    rd = ReadRepository(root / "case.db", load_profile(root)["case_id"])
    try:
        docs = rd.frozen_rows("documents")
    finally:
        rd.close()
    return sorted(d["id"] for d in docs if not (root / "corpus" / _doc_filename(d["id"])).is_file())


def attach_originals(case_dir: Path | str, files: list[str]) -> dict[str, Any]:
    """Re-supply frozen files: each is matched to its Document by SHA-256; any mismatch refuses everything."""
    root = Path(case_dir)
    from .profile import load_profile
    rd = ReadRepository(root / "case.db", load_profile(root)["case_id"])
    try:
        docs = rd.frozen_rows("documents")
    finally:
        rd.close()
    by_sha: dict[str, list[dict[str, Any]]] = {}
    for d in docs:
        by_sha.setdefault(d["sha256"], []).append(d)
    plan: list[tuple[Path, str]] = []
    for f in files:
        p = Path(f)
        if not p.is_file() or p.is_symlink():
            raise _err("E_ORIGINAL_FILE", "The file is missing or not a regular file.", "Plik nie istnieje lub nie jest zwykłym plikiem.",
                       EXIT_PATH, name=p.name)
        h = hashlib.sha256()
        with open(p, "rb") as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b""):
                h.update(chunk)
        match = by_sha.get(h.hexdigest())
        if not match:
            raise _err("E_ORIGINAL_HASH_MISMATCH", "The file does not match any frozen document's SHA-256; nothing was attached.",
                       "Plik nie zgadza się z SHA-256 żadnego zamrożonego dokumentu; niczego nie dołączono.",
                       EXIT_INTEGRITY, name=p.name)
        plan += [(p, _doc_filename(d["id"])) for d in match]
    corpus = root / "corpus"
    corpus.mkdir(exist_ok=True)
    attached = []
    for src, name in plan:
        dst = corpus / name
        tmp = dst.with_name(f".{name}.{uuid.uuid4().hex[:6]}.tmp")
        try:
            shutil.copyfile(src, tmp)
            os.replace(tmp, dst)
        finally:
            if tmp.exists():
                tmp.unlink()
        attached.append(name)
    return {"ok": True, "attached": sorted(attached), "originals_pending": pending_originals(root)}


