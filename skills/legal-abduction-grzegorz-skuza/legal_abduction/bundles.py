def reproduction_manifest(bundle: Path | str, *, report_sha256: str, report_name: str = "report.md") -> dict[str, Any]:
    """Bind a report hash to a bundle hash and the code version, outside the bundle (no circular hash)."""
    members = _read_members(Path(bundle), LIMITS)
    m = _parse_manifest(members)
    if not re.fullmatch(r"[0-9a-f]{64}", report_sha256 or ""):
        raise _err("E_REPORT_HASH", "report_sha256 must be a 64-hex SHA-256.", "report_sha256 musi być 64-znakowym SHA-256.")
    return {"format": "lacase-reproduction", "format_version": 1, "report_name": report_name,
            "report_sha256": report_sha256, "bundle_sha256": sha256_hex(Path(bundle).read_bytes()),
            "code_version": __version__, "bundle_code_version": m["code_version"], "schema_version": m["schema_version"],
            "approved_set_hash": m["approved_set_hash"], "chain_head": m["chain_head"],
            "with_originals": False if not m["with_originals"] else True}


def verify_reproduction(manifest: dict[str, Any], bundle: Path | str, report_bytes: bytes) -> dict[str, Any]:
    ok_bundle = manifest.get("bundle_sha256") == sha256_hex(Path(bundle).read_bytes())
    ok_report = manifest.get("report_sha256") == sha256_hex(report_bytes)
    return {"ok": ok_bundle and ok_report, "bundle_matches": ok_bundle, "report_matches": ok_report,
            "code_version_matches": manifest.get("code_version") == __version__}
